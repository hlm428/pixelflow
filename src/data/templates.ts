import type { PromptTemplate, TemplateCategory } from '../types/template';

/**
 * 提示词模板库全量 260 条：风格 100 + 运镜 50 + 光线 40 + 情绪 30 + 场景 40。
 * 每条带中文说明、使用场景和标签。首次启动自动灌库（模板表为空时）。
 */

type Row = [content: string, description: string, scene: string, tags: string];

function build(cat: TemplateCategory, prefix: string, rows: Row[]): PromptTemplate[] {
  return rows.map(([content, description, scene, tags], i) => ({
    id: `${prefix}-${String(i + 1).padStart(2, '0')}`,
    category: cat,
    content,
    description,
    scene,
    tags: tags.split(' ').filter(Boolean),
    favorite: false,
  }));
}

